CREATE TABLE IF NOT EXISTS `studio_bookings` (
	`id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
	`public_token` CHAR(40) NOT NULL,
	`service` ENUM('pilates','yoga','beauty') NOT NULL,
	`package_id` INT UNSIGNED NOT NULL,
	`package_name` VARCHAR(100) NOT NULL,
	`package_kind` VARCHAR(20) NOT NULL,
	`session_count` SMALLINT UNSIGNED NOT NULL,
	`bonus_sessions` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	`participants` TINYINT UNSIGNED NOT NULL DEFAULT 1,
	`validity_days` SMALLINT UNSIGNED DEFAULT NULL,
	`price` INT UNSIGNED NOT NULL,
	`full_name` VARCHAR(100) NOT NULL,
	`phone` VARCHAR(24) NOT NULL,
	`health_notes` VARCHAR(1000) DEFAULT NULL,
	`source` VARCHAR(40) NOT NULL,
	`source_other` VARCHAR(120) DEFAULT NULL,
	`statement_file` VARCHAR(255) DEFAULT NULL,
	`payment_method` ENUM('qris','transfer') NOT NULL,
	`payment_status` ENUM('pending','paid','rejected') NOT NULL DEFAULT 'pending',
	`booking_status` ENUM('pending_payment','confirmed','expired','cancelled') NOT NULL DEFAULT 'pending_payment',
	`receipt_file` VARCHAR(255) DEFAULT NULL,
	`expires_at` DATETIME NOT NULL,
	`created_at` DATETIME NOT NULL,
	`paid_at` DATETIME DEFAULT NULL,
	`verified_by` INT UNSIGNED DEFAULT NULL,
	`verified_at` DATETIME DEFAULT NULL,
	PRIMARY KEY (`id`),
	UNIQUE KEY `uq_studio_booking_token` (`public_token`),
	KEY `idx_studio_booking_pending` (`booking_status`,`expires_at`),
	KEY `idx_studio_booking_payment` (`payment_status`,`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `studio_booking_sessions` (
	`id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
	`booking_id` BIGINT UNSIGNED NOT NULL,
	`schedule_id` INT UNSIGNED NOT NULL,
	`session_date` DATE NOT NULL,
	`start_time` TIME NOT NULL,
	`coach_name` VARCHAR(60) DEFAULT NULL,
	`class_type` VARCHAR(20) NOT NULL,
	`attendees` TINYINT UNSIGNED NOT NULL DEFAULT 1,
	`is_exclusive` TINYINT(1) NOT NULL DEFAULT 0,
	PRIMARY KEY (`id`),
	UNIQUE KEY `uq_booking_schedule_date` (`booking_id`,`schedule_id`,`session_date`),
	KEY `idx_booked_schedule_date` (`schedule_id`,`session_date`,`start_time`),
	CONSTRAINT `fk_booking_session_booking`
		FOREIGN KEY (`booking_id`) REFERENCES `studio_bookings` (`id`) ON DELETE CASCADE,
	CONSTRAINT `fk_booking_session_schedule`
		FOREIGN KEY (`schedule_id`) REFERENCES `class_schedules` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

